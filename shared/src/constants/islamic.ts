export const DEFAULT_INTERVAL_MINUTES = 60;
export const DEFAULT_ANTI_REPEAT_MINUTES = 180;

/** أقصى عدد عناصر محفوظة في سجل منع التكرار */
export const RECENTLY_SENT_MAX = 25;

/** تصفية أنواع المحتوى: يحتفظ بالأنواع المعروفة فقط، ويعيد الافتراضي إذا لم يتبق شيء */
export function normalizeContentTypes(types: string[]): string[] {
  const known: string[] = ISLAMIC_CONTENT_TYPES.map((t) => t.id);
  const valid = (types ?? []).filter((t) => known.includes(t));
  return valid.length ? [...new Set(valid)] : [...known];
}

/** تصفية مصادر الأحاديث: المصادر المعروفة فقط (Bukhari/Muslim) */
export function normalizeHadithSources(sources: string[]): string[] {
  const known: string[] = ISLAMIC_HADITH_SOURCES.map((s) => s.id);
  const valid = (sources ?? []).filter((s) => known.includes(s));
  return valid.length ? [...new Set(valid)] : [...known];
}

/** تصفية تصنيفات الأذكار: أسماء موجودة في المكتبة فقط */
export function normalizeAzkarCategories(categories: string[]): string[] {
  const valid = (categories ?? []).filter((c) => AZKAR_CATEGORIES.includes(c));
  return valid.length ? [...new Set(valid)] : [...DEFAULT_AZKAR_CATEGORIES];
}

/** الإعدادات الافتراضية لنظام الأذكار */
export function createDefaultIslamicContent() {
  return {
    enabled: false,
    channelId: null as string | null,
    intervalMinutes: DEFAULT_INTERVAL_MINUTES,
    contentTypes: ISLAMIC_CONTENT_TYPES.map((t) => t.id),
    allowedSources: ISLAMIC_HADITH_SOURCES.map((s) => s.id),
    azkarCategories: [...DEFAULT_AZKAR_CATEGORIES],
    antiRepeatMinutes: DEFAULT_ANTI_REPEAT_MINUTES,
    recentlySent: [] as { id: string; at: string }[]
  };
}