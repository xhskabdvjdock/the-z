export function randomTrivia(count: number): TriviaQuestion[] {
  const pool = [...TRIVIA];
  const out: TriviaQuestion[] = [];
  for (let i = 0; i < count && pool.length; i++) {
    const idx = Math.floor(Math.random() * pool.length);
    out.push(pool.splice(idx, 1)[0]);
  }
  return out;
}